import arabicMessages from './arabicMessages.json';
import arabicInline from './arabicInline.json';
import { CORE_ARABIC } from '../../../../../frontend-kit';

export type MessageKey = keyof typeof messages;
/** R123: three-locale engine contract — Arabic resolves through the authored
 *  retro dictionary first, then the shared Core Arabic dictionary (keyed by
 *  the English string), then stays truthful English. */
export type Language = 'en' | 'fa' | 'ar';
export type MessageParams = Record<string, string | number>;

const ARABIC: Readonly<Record<string, string>> = arabicMessages as Readonly<Record<string, string>>;

export function translate(language: Language, key: MessageKey, params: MessageParams = {}): string {
  let template: string;
  if (language === 'ar') {
    template = ARABIC[key] ?? CORE_ARABIC[messages[key][0]] ?? messages[key][0];
  } else {
    template = messages[key][language === 'fa' ? 1 : 0];
  }
  return template.replace(/\{(\w+)\}/g, (_, name: string) => String(params[name] ?? `{${name}}`));
}

const ARABIC_INLINE: Readonly<Record<string, string>> = arabicInline as Readonly<Record<string, string>>;

/** R123: inline L(en, fa) call sites resolve Arabic through the authored inline
 *  dictionary, then the message-key dictionary, then Core, then English. */
export function retroText(language: Language, english: string, persian: string): string {
  if (language === 'en') return english;
  if (language === 'fa') return persian;
  if (Object.hasOwn(ARABIC_INLINE, english)) return ARABIC_INLINE[english];
  const key = (Object.keys(messages) as MessageKey[]).find(k => messages[k][0] === english);
  if (key && Object.hasOwn(ARABIC, key)) return ARABIC[key];
  if (Object.hasOwn(CORE_ARABIC, english)) return CORE_ARABIC[english];
  return english;
}
