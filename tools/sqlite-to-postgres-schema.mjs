#!/usr/bin/env node
// tools/sqlite-to-postgres-schema.mjs — convert the live D1 SQLite schema into a
// complete, idempotent PostgreSQL DDL for the Supabase canonical database.
//
// Input : sandbox/d1-live-schema.json  (from tools/d1-pull-schema.mjs)
// Output: sandbox/postgres-full-schema.sql   (tables + indexes + compat view)
//         sandbox/postgres-full-fks.sql      (FK constraints, applied after data load)
//
// Conversion rules
//   INTEGER  -> bigint (SQLite INTEGER is 64-bit)
//   REAL     -> double precision
//   BLOB     -> bytea
//   TEXT     -> text (timestamps stay TEXT for exact D1 wire parity — the worker's
//              Postgres adapter casts with ::timestamptz on comparison sites)
//   DEFAULT CURRENT_TIMESTAMP -> DEFAULT (CURRENT_TIMESTAMP::text)
//   INTEGER PRIMARY KEY AUTOINCREMENT -> bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY
//   COLLATE NOCASE -> stripped (functional lower() indexes emitted instead where the
//                     original column/index was UNIQUE ... COLLATE NOCASE)
//   REFERENCES ... -> moved to a post-load ALTER TABLE (guarded, skip-on-dirty-data)
//   CHECK constraints, composite PRIMARY KEY / UNIQUE -> kept verbatim
//   FTS5 virtual tables + their shadow tables -> excluded (Postgres uses tsvector/pg_trgm)
//
import { readFileSync, writeFileSync } from "node:fs";

const schemaPath = process.argv[2] ?? "sandbox/d1-live-schema.json";
const rows = JSON.parse(readFileSync(schemaPath, "utf8"));

const VIRTUAL_TABLES = (t) => /CREATE\s+VIRTUAL\s+TABLE/i.test(t.sql ?? "");
const SHADOW_TABLE = (name) =>
  name.startsWith("horse_search_fts_") ||
  name.startsWith("horse_search_trigram_") ||
  name.startsWith("horse_role_search_trigram_");

const tables = rows
  .filter((r) => r.type === "table" && !VIRTUAL_TABLES(r) && !SHADOW_TABLE(r.name))
  .map((r) => ({ name: r.name, sql: r.sql }));
const indexes = rows.filter((r) => r.type === "index" && r.sql && !SHADOW_TABLE(r.tbl_name ?? r.name) && !VIRTUAL_TABLES({ sql: "" }));

function splitTopLevel(body) {
  const parts = [];
  let depth = 0;
  let quote = null;
  let current = "";
  for (const ch of body) {
    if (quote) {
      current += ch;
      if (ch === quote) quote = null;
      continue;
    }
    if (ch === "'" || ch === '"' || ch === "`") {
      quote = ch;
      current += ch;
      continue;
    }
    if (ch === "(") depth++;
    if (ch === ")") depth--;
    if (ch === "," && depth === 0) {
      parts.push(current.trim());
      current = "";
      continue;
    }
    current += ch;
  }
  if (current.trim()) parts.push(current.trim());
  return parts;
}

const FK_ACTIONS = /(?:\s+ON\s+DELETE\s+(?:CASCADE|RESTRICT|NO\s+ACTION|SET\s+NULL|SET\s+DEFAULT))*(?:\s+ON\s+UPDATE\s+(?:CASCADE|RESTRICT|NO\s+ACTION|SET\s+NULL|SET\s+DEFAULT))*/i;
const foreignKeys = []; // { table, column, refTable, refColumn, onDelete, onUpdate }
const ciUniqueColumns = []; // { table, column } — UNIQUE COLLATE NOCASE columns → functional unique index
const integerPkColumns = []; // { table, column } — rowid-alias PKs needing NULL->nextval parity

/** Find a balanced-paren substring starting at the given index of `s` (must be '('). */
function balancedParens(s, start) {
  let depth = 0;
  for (let i = start; i < s.length; i++) {
    if (s[i] === "'") {
      i++;
      while (i < s.length && s[i] !== "'") i++;
      continue;
    }
    if (s[i] === "(") depth++;
    if (s[i] === ")") {
      depth--;
      if (depth === 0) return s.slice(start, i + 1);
    }
  }
  throw new Error("Unbalanced parens in: " + s.slice(start, start + 60));
}

function convertColumn(table, raw) {
  let def = raw.replace(/\s+/g, " ").trim();
  const m = def.match(/^("([^"]+)"|\[([^\]]+)\]|([A-Za-z_][A-Za-z0-9_]*))\s+(.*)$/s);
  if (!m) throw new Error(`Unparsable column def in ${table}: ${raw}`);
  const colName = (m[2] ?? m[3] ?? m[4]).replace(/"/g, "");
  let rest = m[5];

  // 1) REFERENCES -> collect FK, then remove from rest (before other parsing)
  const rm = rest.match(new RegExp(`\\bREFERENCES\\s+([A-Za-z_][A-Za-z0-9_]*)\\s*\\(\\s*([A-Za-z_][A-Za-z0-9_]*)\\s*\\)((?:\\s+ON\\s+DELETE\\s+(?:CASCADE|RESTRICT|NO\\s+ACTION|SET\\s+NULL|SET\\s+DEFAULT))?(?:\\s+ON\\s+UPDATE\\s+(?:CASCADE|RESTRICT|NO\\s+ACTION|SET\\s+NULL|SET\\s+DEFAULT))?)`, "i"));
  if (rm) {
    const onDelete = (rm[0].match(/\bON\s+DELETE\s+(CASCADE|RESTRICT|NO\s+ACTION|SET\s+NULL|SET\s+DEFAULT)/i)?.[1] ?? "NO ACTION").toUpperCase().replace(/\s+/g, " ");
    const onUpdate = (rm[0].match(/\bON\s+UPDATE\s+(CASCADE|RESTRICT|NO\s+ACTION|SET\s+NULL|SET\s+DEFAULT)/i)?.[1] ?? "NO ACTION").toUpperCase().replace(/\s+/g, " ");
    foreignKeys.push({ table, column: colName, refTable: rm[1], refColumn: rm[2], onDelete, onUpdate });
    rest = rest.slice(0, rm.index) + rest.slice(rm.index + rm[0].length);
  }

  // 2) CHECK — balanced parens from the CHECK keyword
  let checkSql = null;
  const checkIdx = rest.search(/\bCHECK\s*\(/i);
  if (checkIdx >= 0) {
    const openIdx = rest.indexOf("(", checkIdx);
    checkSql = balancedParens(rest, openIdx);
    rest = (rest.slice(0, checkIdx) + " " + rest.slice(openIdx + checkSql.length)).replace(/\s+/g, " ").trim();
  }

  // 3) Type
  let pgType = "text";
  const autoinc = /AUTOINCREMENT/i.test(rest);
  const pkInline = /\bPRIMARY\s+KEY\b/i.test(rest);
  if (/^INTEGER/i.test(rest)) {
    pgType = "bigint";
    rest = rest.replace(/^INTEGER(\s+PRIMARY\s+KEY)?(\s+AUTOINCREMENT)?/i, (full) => full).replace(/^INTEGER/i, "");
  } else if (/^TEXT/i.test(rest)) {
    rest = rest.replace(/^TEXT/i, "");
  } else if (/^REAL/i.test(rest)) {
    pgType = "double precision";
    rest = rest.replace(/^REAL/i, "");
  } else if (/^BLOB/i.test(rest)) {
    pgType = "bytea";
    rest = rest.replace(/^BLOB/i, "");
  } else if (/^NUMERIC/i.test(rest)) {
    pgType = "numeric";
    rest = rest.replace(/^NUMERIC([^\s]*)/i, "");
  }
  if (pkInline && pgType === "bigint") {
    // SQLite INTEGER PRIMARY KEY is a rowid alias: a NULL id auto-assigns
    // max+1. Postgres identity (BY DEFAULT) mirrors that while still
    // accepting explicit ids from syncs/imports.
    pgType = "bigint GENERATED BY DEFAULT AS IDENTITY";
    rest = rest.replace(/PRIMARY\s+KEY/i, "").replace(/AUTOINCREMENT/i, "");
    integerPkColumns.push({ table, column: colName });
  }
  let out = `${q(colName)} ${pgType}`;
  // PRIMARY KEY (inline; autoincrement columns carry it too)
  if (pkInline) out += " PRIMARY KEY";
  // NOT NULL
  if (/\bNOT\s+NULL\b/i.test(rest)) out += " NOT NULL";
  // DEFAULT
  const dm = rest.match(/\bDEFAULT\s+('(?:[^']|'')*'|"(?:[^"]|"")*"|-?\d+(?:\.\d+)?|NULL|CURRENT_TIMESTAMP)(?=[\s,)]|$)/i);
  if (dm) {
    let dv = dm[1];
    if (/^CURRENT_TIMESTAMP$/i.test(dv)) dv = "(CURRENT_TIMESTAMP::text)";
    out += ` DEFAULT ${dv}`;
  }
  // UNIQUE — plain inline only; NOCASE-unique is handled via functional index at table level
  const hasUnique = /\bUNIQUE\b/i.test(rest);
  const uniqueCi = hasUnique && /COLLATE\s+NOCASE/i.test(rest);
  if (hasUnique && !uniqueCi) out += " UNIQUE";
  if (checkSql) out += ` CHECK ${checkSql}`;
  if (uniqueCi) ciUniqueColumns.push({ table, column: colName });
  return out;
}

function q(name) {
  return `"${name}"`;
}

function convertTableConstraint(table, raw) {
  let def = raw.replace(/\s+/g, " ").trim();
  // FOREIGN KEY(...) REFERENCES ... -> collect
  const fm = def.match(/^FOREIGN\s+KEY\s*\(\s*([^)]+)\s*\)\s*REFERENCES\s+([A-Za-z_][A-Za-z0-9_]*)\s*\(\s*([A-Za-z_][A-Za-z0-9_]*)\s*\)/i);
  if (fm) {
    const column = fm[1].replace(/"/g, "").trim();
    const onDelete = (def.match(/\bON\s+DELETE\s+(CASCADE|RESTRICT|NO\s+ACTION|SET\s+NULL|SET\s+DEFAULT)/i)?.[1] ?? "NO ACTION").toUpperCase();
    foreignKeys.push({ table, column, refTable: fm[2], refColumn: fm[3], onDelete, onUpdate: "NO ACTION" });
    return null;
  }
  // PRIMARY KEY(a,b) / UNIQUE(a,b) / CHECK(...) / CONSTRAINT name ...
  def = def.replace(/\bCOLLATE\s+NOCASE/ig, "");
  return def;
}

const outSql = [];
const identityTables = [];

outSql.push(`-- Generated by tools/sqlite-to-postgres-schema.mjs from live D1 schema
-- Supabase canonical full schema (R59). Idempotent: safe to re-run.
BEGIN;

CREATE EXTENSION IF NOT EXISTS pg_trgm;
`);

for (const t of tables) {
  const bodyMatch = t.sql.match(/\(([\s\S]*)\)\s*$/);
  if (!bodyMatch) throw new Error(`Cannot parse table body: ${t.name}`);
  const parts = splitTopLevel(bodyMatch[1]);
  const lines = [];
  for (const part of parts) {
    if (/^(PRIMARY\s+KEY|UNIQUE|CHECK|FOREIGN\s+KEY|CONSTRAINT)\b/i.test(part)) {
      const converted = convertTableConstraint(t.name, part);
      if (converted) lines.push("  " + converted);
      continue;
    }
    lines.push("  " + convertColumn(t.name, part));
  }
  if (/AUTOINCREMENT/i.test(t.sql)) identityTables.push(t.name);
  outSql.push(`CREATE TABLE IF NOT EXISTS ${q(t.name)} (\n${lines.join(",\n")}\n);`);
  outSql.push("");
}

// Indexes from sqlite_master (non-shadow tables only)
outSql.push(`-- Indexes (converted from D1)`);
for (const idx of indexes) {
  let sql = idx.sql.replace(/\s+/g, " ").trim();
  // skip indexes on excluded (FTS/shadow) tables
  const target = sql.match(/ON\s+([A-Za-z_][A-Za-z0-9_]*)/i)?.[1];
  if (!target || SHADOW_TABLE(target) || VIRTUAL_TABLES({ sql })) continue;
  sql = sql.replace(/\bCOLLATE\s+NOCASE/ig, "");
  // SQLite function parity inside index expressions: IFNULL(a, b) is exactly
  // COALESCE(a, b) in PostgreSQL (R81: migration 0030's uq_competition_results_entry
  // surfaced this — the index DDL otherwise failed on Supabase apply).
  sql = sql.replace(/\bIFNULL\s*\(/gi, "COALESCE(");
  sql = sql.replace(/^CREATE\s+(UNIQUE\s+)?INDEX\s+(?:IF\s+NOT\s+EXISTS\s+)?([A-Za-z_][A-Za-z0-9_]*)\s*/i,
    (_m, uniq, name) => `CREATE ${uniq ?? ""}INDEX IF NOT EXISTS "${name}" `);
  // DESC inside index column lists is supported by PG — keep
  outSql.push(sql.replace(/;\s*$/, "") + ";");
}
outSql.push("");

// Case-insensitive unique indexes for NOCASE unique columns
ciUniqueColumns.length || outSql.push(`-- (no NOCASE-unique columns)`);
for (const { table, column } of ciUniqueColumns) {
  outSql.push(`CREATE UNIQUE INDEX IF NOT EXISTS ${q(`uq_${table}_${column}_ci`)} ON ${q(table)} (lower(${q(column)}));`);
}

// SQLite rowid-alias parity: an explicit NULL into INTEGER PRIMARY KEY
// auto-assigns in SQLite but NOT into a Postgres identity column. These
// BEFORE INSERT triggers restore the D1 contract for every integer PK.
for (const { table, column } of integerPkColumns) {
  const fn = `__assign_${table}_${column}_pk`;
  outSql.push(`CREATE OR REPLACE FUNCTION ${q(fn)}() RETURNS trigger AS $fn$
BEGIN
  IF NEW.${q(column)} IS NULL THEN
    NEW.${q(column)} := nextval(pg_get_serial_sequence('${table}', '${column}'));
  END IF;
  RETURN NEW;
END $fn$ LANGUAGE plpgsql;
DROP TRIGGER IF EXISTS ${q(`trg_${table}_${column}_assign`)} ON ${q(table)};
CREATE TRIGGER ${q(`trg_${table}_${column}_assign`)} BEFORE INSERT ON ${q(table)}
  FOR EACH ROW EXECUTE FUNCTION ${q(fn)}();`);
}

// sqlite_master compatibility view (aiStorageReady probes it)
outSql.push(`
-- Compatibility view: the AI storage readiness probe reads sqlite_master.
CREATE OR REPLACE VIEW sqlite_master AS
  SELECT c.relname AS name,
         CASE c.relkind WHEN 'r' THEN 'table' WHEN 'v' THEN 'view' WHEN 'm' THEN 'view' ELSE c.relkind::text END AS type,
         c.relname AS tbl_name,
         NULL::text AS sql
  FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
  WHERE n.nspname = 'public' AND c.relkind IN ('r','v','m');

COMMIT;
`);

// FK file — applied AFTER data load so pre-existing rows are validated once.
const fkSql = [`-- Foreign keys (applied post data-load; skipped individually if legacy data violates them)
BEGIN;
`];
for (const fk of foreignKeys) {
  fkSql.push(`DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint c
    JOIN pg_class t ON t.oid = c.conrelid
    JOIN pg_namespace n ON n.oid = t.relnamespace
    WHERE n.nspname='public' AND t.relname='${fk.table}' AND c.contype='f' AND c.conname='${`fk_${fk.table}_${fk.column}`}'
  ) THEN
    BEGIN
      ALTER TABLE ${q(fk.table)} ADD CONSTRAINT ${q(`fk_${fk.table}_${fk.column}`)}
        FOREIGN KEY (${q(fk.column)}) REFERENCES ${q(fk.refTable)} (${q(fk.refColumn)})
        ON DELETE ${fk.onDelete} ON UPDATE ${fk.onUpdate};
    EXCEPTION WHEN foreign_key_violation OR invalid_object_definition THEN
      RAISE NOTICE 'FK ${fk.table}.${fk.column} -> ${fk.refTable} skipped: legacy data violates it';
    END;
  END IF;
END $$;`);
}
fkSql.push(`\nCOMMIT;`);

writeFileSync("sandbox/postgres-full-schema.sql", outSql.join("\n"));
writeFileSync("sandbox/postgres-full-fks.sql", fkSql.join("\n"));
console.log(`tables: ${tables.length}, indexes: ${indexes.length}, fks: ${foreignKeys.length}, identity tables: ${identityTables.length}`);
console.log("written: sandbox/postgres-full-schema.sql + sandbox/postgres-full-fks.sql");
