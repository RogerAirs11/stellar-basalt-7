/* Rebuild the vanilla frontend's semantic model from the single TS authority. */
const fs = require('node:fs');
const path = require('node:path');
let ts;
try { ts = require('typescript'); } catch { ts = require(path.join(require('node:child_process').execSync('npm root -g', {encoding:'utf8'}).trim(), 'typescript')); }
const root = path.resolve(__dirname, '..');
const input = path.join(root, 'src/frontend-kit/navigation.ts');
const output = path.join(root, 'standalone-frontends/classic-v1.4/public/ui/navigationModel.js');
const result = '// GENERATED by tools/build-navigation-model.cjs. Edit src/frontend-kit/navigation.ts instead.\n' + ts.transpileModule(fs.readFileSync(input, 'utf8'), {compilerOptions:{target:ts.ScriptTarget.ES2022, module:ts.ModuleKind.ES2022}}).outputText;
if (process.argv.includes('--check')) {
  if (!fs.existsSync(output) || fs.readFileSync(output, 'utf8') !== result) { console.error('Classic navigation model is stale. Run node tools/build-navigation-model.cjs'); process.exitCode=1; }
  else console.log('Classic navigation model matches the shared source.');
} else { fs.writeFileSync(output,result); console.log('Generated Classic semantic navigation model.'); }

const paletteSource = path.join(root, 'src/frontend-kit/navigation-group-tokens.css');
const paletteOut = path.join(root, 'standalone-frontends/classic-v1.4/public/ui/navigationGroupTokens.css');
const palette = fs.readFileSync(paletteSource, 'utf8');
if (process.argv.includes('--check')) {
  if (!fs.existsSync(paletteOut) || fs.readFileSync(paletteOut, 'utf8') !== palette) {
    console.error('Classic navigation palette is stale. Run node tools/build-navigation-model.cjs'); process.exitCode=1;
  }
} else fs.writeFileSync(paletteOut, palette);

const displayInput = path.join(root, 'src/frontend-kit/horseDisplay.ts');
const displayOutput = path.join(root, 'standalone-frontends/classic-v1.4/public/ui/horseDisplay.js');
const displayResult = '// GENERATED: edit src/frontend-kit/horseDisplay.ts, then tools/build-navigation-model.cjs.\n' + ts.transpileModule(fs.readFileSync(displayInput,'utf8'),{compilerOptions:{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.ES2022}}).outputText;
if (process.argv.includes('--check')) {
 if (!fs.existsSync(displayOutput)||fs.readFileSync(displayOutput,'utf8')!==displayResult) { console.error('Classic horse display model is stale.'); process.exitCode=1; }
} else fs.writeFileSync(displayOutput,displayResult);
