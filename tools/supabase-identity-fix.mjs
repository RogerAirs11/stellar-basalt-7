// In-place: attach identity to every integer-PK column on the live Supabase
// schema (mirrors SQLite's INTEGER PRIMARY KEY rowid-alias auto-assign), then
// setval each sequence past the synced data.
import postgres from "postgres";

const SUPA_URL = process.env.SUPABASE_DATABASE_URL;
if (!SUPA_URL) { console.error("Need SUPABASE_DATABASE_URL"); process.exit(1); }
const sql = postgres(SUPA_URL, { prepare: false, max: 1 });

const identityColumns = [
  ["audit_events", "id"], ["breeding_records", "id"], ["change_request_items", "id"],
  ["competition_results", "id"], ["competitions", "id"], ["data_quality_issues", "id"],
  ["genetic_tests", "id"], ["horse_aliases", "id"], ["horse_reference_intelligence", "horse_id"],
  ["horse_registry_people_summary", "horse_id"], ["horse_search_reindex_queue", "horse_id"],
  ["horse_search_source", "horse_id"], ["horses", "id"], ["people", "id"],
  ["person_registry_stats", "person_id"], ["registry_runtime_counters", "id"],
  ["registry_state", "id"], ["source_imports", "id"],
];

for (const [table, col] of identityColumns) {
  const existing = await sql`
    SELECT COUNT(*)::int AS n FROM information_schema.columns
    WHERE table_schema='public' AND table_name=${table} AND column_name=${col}
      AND is_identity='YES'`;
  if (existing[0].n > 0) { console.log(`= ${table}.${col} already identity`); continue; }
  try {
    await sql.unsafe(`ALTER TABLE "${table}" ALTER COLUMN "${col}" ADD GENERATED BY DEFAULT AS IDENTITY`);
    await sql.unsafe(`SELECT setval(pg_get_serial_sequence('${table}', '${col}'), GREATEST(COALESCE((SELECT MAX("${col}") FROM "${table}"), 1), 1))`);
    console.log(`✓ ${table}.${col} -> identity + setval`);
  } catch (e) {
    console.error(`✗ ${table}.${col}: ${e.message}`);
    process.exitCode = 1;
  }
}

// sanity: identity columns present
const total = await sql`
  SELECT COUNT(*)::int AS n FROM information_schema.columns
  WHERE table_schema='public' AND is_identity='YES'`;
console.log("total identity columns:", total[0].n);
await sql.end({ timeout: 2 });
