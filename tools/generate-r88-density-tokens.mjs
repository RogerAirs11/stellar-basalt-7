/** Each frontend owns its token values and independent CSS. This generator only
 * enforces the same semantic vocabulary; it does not merge visual identities. */
import { readFileSync, writeFileSync } from 'node:fs';
const skins = [
  ['src/web/frontends/equidata-elite', '.equidata-elite-ui', 'edx'],
  ['src/web/frontends/fei-classic', '.fei-classic-ui', 'fc'],
  ['src/web/frontends/retro-astra/transplant', '.retro-astra-transplant', 'ra'],
  ['standalone-frontends/classic-v1.4/public/ui', 'body[data-classic-registry]', 'cr'],
];
for (const [dir, scope, prefix] of skins) {
  const data = JSON.parse(readFileSync(`${dir}/density.tokens.json`, 'utf8'));
  for (const [key, value] of Object.entries(data)) {
    if (!/^[a-z][a-z0-9-]+$/.test(key) || !Number.isFinite(value) || value < 0 || value > 2000) throw new Error(`Invalid ${prefix} token ${key}`);
  }
  const css = `/* Generated by tools/generate-r88-density-tokens.mjs; edit this skin's density.tokens.json. */\n${scope} {\n${Object.entries(data).map(([k,v]) => `  --${prefix}-compact-${k}: ${v}px;`).join('\n')}\n}\n`;
  if (process.argv.includes('--check')) {
    if (readFileSync(`${dir}/density-tokens.css`, 'utf8') !== css) throw new Error(`Stale generated tokens: ${dir}`);
  } else writeFileSync(`${dir}/density-tokens.css`, css);
}
console.log('Four independent density token sets are consistent.');
