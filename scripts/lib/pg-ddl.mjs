/**
 * Shared SQLite→PostgreSQL migration-chain machinery (single source of truth).
 *
 * Used by BOTH:
 *   - scripts/pg-parity-gate.mjs      (DDL parity: the chain applies cleanly)
 *   - scripts/pg-execution-parity.mjs (P01 execution parity: same seed +
 *     command sequence on a real PostgreSQL in an isolated schema)
 *
 * Keeping the splitting/normalization/translation rules in ONE place means the
 * two gates can never drift apart.
 */
import { readFileSync, readdirSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { compileTsRuntime } from "../../tools/ts-runtime-loader.mjs";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "..");

/** Split SQL into statements, respecting quotes and comments (no triggers in the corpus). */
export function splitStatements(text) {
  const out = [];
  let current = "";
  let inSingle = false, inDouble = false, inLine = false, inBlock = false;
  for (let i = 0; i < text.length; i++) {
    const ch = text[i];
    const next = text[i + 1];
    if (inLine) { current += ch; if (ch === "\n") inLine = false; continue; }
    if (inBlock) { current += ch; if (ch === "*" && next === "/") { current += next; i++; inBlock = false; } continue; }
    if (!inSingle && !inDouble && ch === "-" && next === "-") { inLine = true; current += ch; continue; }
    if (!inSingle && !inDouble && ch === "/" && next === "*") { inBlock = true; current += ch; continue; }
    if (ch === "'" && !inDouble) inSingle = !inSingle;
    else if (ch === '"' && !inSingle) inDouble = !inDouble;
    current += ch;
    if (ch === ";" && !inSingle && !inDouble) { out.push(current.trim()); current = ""; }
  }
  if (current.trim()) out.push(current.trim());
  return out.filter(statement => statement.length > 1);
}

/**
 * DDL normalization for migration files — the SAME rules the production schema
 * tool (tools/sqlite-to-postgres-schema.mjs) documents, applied here so the
 * migration chain alone can build the primary-DB schema. The runtime translator
 * stays untouched (it serves queries, not DDL).
 */
export function ddlNormalize(statement) {
  let value = statement;
  value = value.replace(/\bINTEGER\s+PRIMARY\s+KEY\s+AUTOINCREMENT\b/gi, "bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY");
  value = value.replace(/\bINTEGER\s+PRIMARY\s+KEY\b(?!\s+AUTOINCREMENT)/gi, "bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY");
  value = value.replace(/\bAUTOINCREMENT\b/gi, "");
  value = value.replace(/\bINTEGER\b/g, "bigint");
  value = value.replace(/\bREAL\b/g, "double precision");
  value = value.replace(/\bBLOB\b/g, "bytea");
  value = value.replace(/\s+COLLATE\s+NOCASE\b/g, "");
  return value;
}

/** Compile the PRODUCTION runtime translator (src/db/sqliteSqlToPostgres.ts). */
export function loadTranslator() {
  const rt = compileTsRuntime(["src/db/sqliteSqlToPostgres.ts"], { root });
  const mod = rt.load("src/db/sqliteSqlToPostgres.ts");
  return { sqliteSqlToPostgres: mod.sqliteSqlToPostgres, stripLeadingComments: mod.stripLeadingComments };
}

/**
 * Apply the full migrations/*.sql chain through the production translator.
 *
 * `sql` must be a postgres.js client bound to the target schema (the caller
 * sets search_path — typically an isolated disposable schema, never `public`
 * on a live database). Returns { applied, skippedFts } and THROWS on the first
 * failing statement so the caller can fail closed.
 */
export async function applyMigrationChain(sql) {
  const { sqliteSqlToPostgres, stripLeadingComments } = loadTranslator();
  const migrations = readdirSync(join(root, "migrations"))
    .filter(name => name.endsWith(".sql"))
    .sort();
  if (!migrations.length) throw new Error("No migrations found");

  let skippedFts = 0;
  for (const name of migrations) {
    const raw = readFileSync(join(root, "migrations", name), "utf8");
    await sql.unsafe("BEGIN");
    try {
      for (const statement of splitStatements(raw)) {
        const bare = stripLeadingComments(statement);
        if (/^\s*PRAGMA\b/i.test(bare)) continue; // connection-level SQLite directive
        if (/^\s*CREATE\s+VIRTUAL\s+TABLE/i.test(bare)) {
          // Production mapping: Postgres serves FTS via horse_search_source
          // (tsvector + pg_trgm); FTS5 shadow tables are D1-only.
          skippedFts += 1;
          continue;
        }
        const translated = sqliteSqlToPostgres(ddlNormalize(statement));
        if (!translated.trim() || !stripLeadingComments(translated).trim()) continue;
        await sql.unsafe(translated);
      }
      await sql.unsafe("COMMIT");
    } catch (error) {
      await sql.unsafe("ROLLBACK");
      throw new Error(`migration ${name} failed on PostgreSQL: ${error instanceof Error ? error.message : String(error)}`);
    }
  }
  return { applied: migrations.length, skippedFts };
}
